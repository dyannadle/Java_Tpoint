public class ladderEx {
    public static void main(String[] args) {
        int a = 90, b = 50;
        if (a > b) {
            System.out.println(a + "is greater than" + b);
        } else if (a < b) {
            System.out.println(a + "is lesser than" + b);

        } else {
            System.out.println("Both are Equal");
        }
    }
}
