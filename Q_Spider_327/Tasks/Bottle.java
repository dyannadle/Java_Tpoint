package Q_Spider_327.Tasks;

public class Bottle {
    // Private variables (data is hidden from outside)
    private String color; // stores the color of the bottle
    private int capacity; // stores capacity in ml

    // Setter method to set color
    public void setColor(String c) {
        color = c; // assign value to color
    }

    // Setter method to set capacity
    public void setCapacity(int cap) {
        capacity = cap; // assign value to capacity
    }

    // Getter method to get color
    public String getColor() {
        return color; // return color value
    }

    // Getter method to get capacity
    public int getCapacity() {
        return capacity; // return capacity value
    }
}